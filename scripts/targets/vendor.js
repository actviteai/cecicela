'use strict';

/**
 * Copies that keep each npm package self-contained:
 *
 *   packages/core/lib/*.js  -> packages/<pkg>/lib/core/   (minus tui.js)
 *   packages/core/lib/tui.js -> packages/ceci/skill/tool/tui.js
 *   LICENSE                 -> packages/<pkg>/LICENSE
 *
 * core is private and never published, so it travels inside each tarball.
 */

const fs = require('fs');
const path = require('path');
const { REPO, PUBLISHED } = require('../lib/repo');

const BANNER = '// Generated by `npm run sync` from packages/core/lib. Edit the source, not this copy.\n';

function coreFiles() {
  const dir = path.join(REPO, 'packages', 'core', 'lib');
  const files = new Map();
  for (const name of fs.readdirSync(dir).sort()) {
    if (!name.endsWith('.js') || name === 'tui.js') continue;
    const text = fs.readFileSync(path.join(dir, name), 'utf8');
    files.set(name, { text: text.startsWith("'use strict';") ? `${BANNER}${text}` : text, exec: false });
  }
  return files;
}

function targets() {
  const out = [];
  const core = coreFiles();
  for (const pkg of PUBLISHED) {
    out.push({ out: `packages/${pkg}/lib/core`, why: 'npm packs real files only', modes: false, files: core });
    out.push({
      out: `packages/${pkg}`,
      why: 'npm packs a package-local LICENSE',
      modes: false,
      sweep: false,
      files: new Map([['LICENSE', { text: fs.readFileSync(path.join(REPO, 'LICENSE'), 'utf8'), exec: false }]]),
    });
  }
  out.push({
    out: 'packages/ceci/skill/tool',
    why: 'the engine loads it next to itself in every installed copy',
    modes: false,
    sweep: false,
    files: new Map([['tui.js', { text: fs.readFileSync(path.join(REPO, 'packages', 'core', 'lib', 'tui.js'), 'utf8'), exec: false }]]),
  });
  return out;
}

module.exports = { targets };
